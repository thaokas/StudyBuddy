/**
 * Build the StudyBuddy appearance client bundle.
 *
 * The plugin has one hand-written entry and inlines the buddy PNG as a data URL
 * so the artwork works offline. The shared builder in study-core resolves
 * esbuild, wraps the module-loader handoff, writes the artifact and hashes it.
 */
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join, resolve } from 'node:path';
import * as shared from '../../study-core/scripts/build-client.mjs';

/** Plugin package root. */
export const PLUGIN_ROOT = fileURLToPath(new URL('..', import.meta.url));

/** Browser entry module. */
export const ENTRY_FILE = join(PLUGIN_ROOT, 'client/plugin.js');

/** Built bundle, also this package's `exports["./client"]` target. */
export const OUTPUT_FILE = join(PLUGIN_ROOT, 'client/client.js');

/** Pinned DSH source checkout that provides esbuild when this package has no install. */
export const SOURCE_ROOT = shared.SOURCE_ROOT;

/** Registration id, which must equal the package name the Loader row resolves. */
export const BUNDLE_ID = '@studybuddy/study-appearance';

/** Generated-file comment for this bundle. */
const HEADER = 'StudyBuddy appearance client bundle — generated by plugins/study-appearance/scripts/build-client.mjs. Do not edit.';

/** Load esbuild from this package, else from the pinned source checkout. */
export const loadEsbuild = () => shared.loadEsbuild(PLUGIN_ROOT);

/** Wrap one CommonJS bundle body in the module-loader handoff. */
export const wrapBundle = (body, id = BUNDLE_ID) => shared.wrapBundle(body, id, HEADER);

/**
 * Build the bundle.
 * @param {{ write?: boolean }} [options] - Set `write: false` for freshness tests.
 * @returns {Promise<{ source: string, bytes: number, sha256: string, output: string }>} Build result.
 */
export const buildClient = (options = {}) => shared.buildSingleEntry({
  pluginRoot: PLUGIN_ROOT,
  entryFile: ENTRY_FILE,
  outputFile: OUTPUT_FILE,
  bundleId: BUNDLE_ID,
  header: HEADER,
  loader: { '.png': 'dataurl' },
  failureLabel: '外观插件打包失败',
  write: options.write !== false,
});

/** Run the build as a command-line tool. */
async function main() {
  try {
    const result = await buildClient();
    console.log(JSON.stringify({ ok: true, bundle: 'client/client.js', id: BUNDLE_ID, bytes: result.bytes, sha256: result.sha256 }, null, 2));
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}

const invokedDirectly = process.argv[1] !== undefined
  && pathToFileURL(resolve(process.argv[1])).href === import.meta.url;
if (invokedDirectly) await main();
