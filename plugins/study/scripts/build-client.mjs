/**
 * Build the StudyBuddy client bundle.
 *
 * 1. Discover `client/pages/*.js`, `client/messages/*.js` and `client/actions/*.js`.
 * 2. Generate the barrel (`client/.build/entry.js`) that imports them and hands
 *    them to `client/plugin.js`.
 * 3. Bundle the barrel with esbuild (`react` stays external: the host module
 *    table supplies it) and wrap the output in the
 *    `window.__ModuleLoader__.load({ id, factory })` handoff the DSH client
 *    module system expects, writing `client/client.js`.
 *
 * The artifact is served straight from this package (`exports["./client"]`),
 * so run this script before starting the app after a client change.
 *
 * esbuild is resolved from this package's `node_modules` when installed, and
 * otherwise from the pinned DSH source checkout, whose dependency store is the
 * only esbuild this workspace has today.
 */
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { mergeMessages, normalizeActions } from '../client/lib/definitions.js';

/** Plugin package root (`plugins/study`). */
export const PLUGIN_ROOT = fileURLToPath(new URL('..', import.meta.url));

/** Source directory for hand-written client modules. */
export const CLIENT_ROOT = join(PLUGIN_ROOT, 'client');

/** Generated barrel the bundle imports. */
export const BARREL_FILE = join(CLIENT_ROOT, '.build', 'entry.js');

/** Built bundle, also this package's `exports["./client"]` target. */
export const OUTPUT_FILE = join(CLIENT_ROOT, 'client.js');

/** Pinned DSH source checkout that provides esbuild when this package has no install. */
export const SOURCE_ROOT = resolve(PLUGIN_ROOT, '../../source/deepseek-harness');

/** Registration id, which must equal the package name the Loader row resolves. */
export const BUNDLE_ID = '@studybuddy/study';

/** Contribution directories, in the order the barrel imports them. */
const DIRECTORIES = Object.freeze(['pages', 'messages', 'actions']);

/** A contribution module file: lowercase start, then lowercase letters, digits or hyphens. */
const MODULE_FILE = /^[a-z][a-z0-9-]*\.js$/;

/**
 * List the module names of one contribution directory.
 * @param {string} directory - Absolute directory path.
 * @returns {Promise<string[]>} Sorted file names without the `.js` suffix.
 * @throws when a `.js` file does not follow the naming rule (a silently
 *   ignored page is a defect, not a convention).
 */
async function listModules(directory) {
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error.code === 'ENOENT') return [];
    throw error;
  }
  const files = entries.filter(entry => entry.isFile() && entry.name.endsWith('.js')).map(entry => entry.name);
  const ignored = files.filter(name => !MODULE_FILE.test(name));
  if (ignored.length > 0) {
    throw new Error(`${directory} 里的文件名必须是小写字母开头、只含小写字母/数字/连字符：${ignored.join('、')}`);
  }
  return files.map(name => name.slice(0, -'.js'.length)).sort();
}

/**
 * Discover the contribution modules and enforce the page/dictionary pairing.
 * @param {string} [clientRoot] - Client source root.
 * @returns {Promise<{ pages: string[], messages: string[], actions: string[] }>} Module names.
 */
export async function discoverContributions(clientRoot = CLIENT_ROOT) {
  const discovered = {};
  for (const name of DIRECTORIES) discovered[name] = await listModules(join(clientRoot, name));
  const unpaired = discovered.pages.filter(page => !discovered.messages.includes(page));
  if (unpaired.length > 0) {
    throw new Error(`每个页面都要有同名文案模块：缺少 client/messages/${unpaired[0]}.js${unpaired.length > 1 ? ` 等 ${unpaired.length} 个` : ''}`);
  }
  return discovered;
}

/**
 * Render the barrel module the bundle imports.
 * @param {{ pages: string[], messages: string[], actions: string[] }} contributions - Discovered modules.
 * @returns {string} Generated module source.
 */
export function renderBarrel({ pages, messages, actions }) {
  const lines = [
    '/* Generated by plugins/study/scripts/build-client.mjs. Do not edit. */',
    "import { createPlugin } from '../plugin.js';",
  ];
  pages.forEach((name, index) => lines.push(`import page${index} from '../pages/${name}.js';`));
  messages.forEach((name, index) => lines.push(`import messages${index} from '../messages/${name}.js';`));
  actions.forEach((name, index) => lines.push(`import action${index} from '../actions/${name}.js';`));
  lines.push('', 'const plugin = createPlugin({', '  pages: [');
  pages.forEach((name, index) => lines.push(`    { file: ${JSON.stringify(name)}, definition: page${index} },`));
  lines.push('  ],', '  messages: [');
  messages.forEach((name, index) => lines.push(`    { file: ${JSON.stringify(name)}, dictionary: messages${index} },`));
  lines.push('  ],', '  actions: [');
  actions.forEach((name, index) => lines.push(`    { file: ${JSON.stringify(name)}, definition: action${index} },`));
  lines.push('  ],', '});', '', 'export const inject = plugin.inject;', 'export const apply = plugin.apply;', '');
  return lines.join('\n');
}

/**
 * Wrap one CommonJS bundle body in the module-loader handoff.
 * @param {string} body - esbuild CommonJS output.
 * @param {string} [id] - Registration id; must equal the package name.
 * @returns {string} Bundle source served to the browser.
 */
export function wrapBundle(body, id = BUNDLE_ID) {
  return [
    '/* StudyBuddy study client bundle — generated by plugins/study/scripts/build-client.mjs. Do not edit. */',
    'window.__ModuleLoader__.load({',
    `  id: ${JSON.stringify(id)},`,
    '  factory(require) {',
    '    const module = { exports: {} };',
    '    const exports = module.exports;',
    body.trimEnd(),
    '    return module.exports;',
    '  },',
    '});',
    '',
  ].join('\n');
}

/**
 * Load esbuild from this package, else from the pinned source checkout.
 * @returns {{ version: string, build: Function }} esbuild's Node API.
 * @throws when no candidate location provides esbuild.
 */
export function loadEsbuild() {
  const candidates = [
    PLUGIN_ROOT,
    SOURCE_ROOT,
    join(SOURCE_ROOT, 'node_modules', '.pnpm', 'node_modules'),
  ];
  const failures = [];
  for (const base of candidates) {
    try {
      return createRequire(join(base, 'package.json'))('esbuild');
    } catch (error) {
      failures.push(`${base}（${error.code ?? error.message}）`);
    }
  }
  throw new Error(`找不到 esbuild，试过：\n  ${failures.join('\n  ')}\n在 plugins/study 下安装依赖，或让固定源码树提供 esbuild。`);
}

/**
 * Validate the modules the build script can evaluate: dictionaries and actions.
 * Page definitions import React and are validated when the bundle is evaluated.
 * @param {{ pages: string[], messages: string[], actions: string[] }} contributions - Discovered modules.
 * @param {string} clientRoot - Client source root.
 * @returns {Promise<{ dictionary: object, actions: Array<object> }>} Validated inputs.
 */
export async function validateContributions(contributions, clientRoot = CLIENT_ROOT) {
  const messages = [];
  for (const name of contributions.messages) {
    const module = await import(pathToFileURL(join(clientRoot, 'messages', `${name}.js`)).href);
    messages.push({ file: name, dictionary: module.default });
  }
  const dictionary = mergeMessages(messages);
  const actions = [];
  for (const name of contributions.actions) {
    const module = await import(pathToFileURL(join(clientRoot, 'actions', `${name}.js`)).href);
    actions.push({ file: name, definition: module.default });
  }
  return { dictionary, actions: normalizeActions(actions, { dictionary, pageKeys: contributions.pages }) };
}

/**
 * Format esbuild's aggregated failure into one readable message.
 * @param {unknown} error - Rejection from `esbuild.build`.
 * @returns {string} Message with one line per problem.
 */
function describeBuildFailure(error) {
  const failures = Array.isArray(error?.errors) ? error.errors : [];
  const details = failures.map(item => {
    const location = item.location === null || item.location === undefined
      ? ''
      : `${item.location.file ?? '?'}:${item.location.line ?? 0} `;
    return `${location}${item.text ?? ''}`;
  });
  return [`esbuild 打包失败：${error instanceof Error ? error.message : String(error)}`, ...details].join('\n');
}

/**
 * Build the client bundle: discover, generate the barrel, validate, bundle, wrap.
 * @param {{ clientRoot?: string, barrelFile?: string, outputFile?: string, write?: boolean }} [options]
 *   Overrides for tests; production uses the exported paths.
 * @returns {Promise<{ contributions: object, barrel: string, output: string, source: string, bytes: number }>}
 *   Build result; `source` is the wrapped bundle text.
 */
export async function buildClient(options = {}) {
  const clientRoot = options.clientRoot ?? CLIENT_ROOT;
  const barrelFile = options.barrelFile ?? BARREL_FILE;
  const outputFile = options.outputFile ?? OUTPUT_FILE;
  const contributions = await discoverContributions(clientRoot);
  const barrel = renderBarrel(contributions);
  await mkdir(dirname(barrelFile), { recursive: true });
  await writeFile(barrelFile, barrel);
  await validateContributions(contributions, clientRoot);

  const esbuild = loadEsbuild();
  let result;
  try {
    result = await esbuild.build({
      // Pin the path base so the module comments (and therefore the served
      // bytes) do not depend on the caller's working directory.
      absWorkingDir: clientRoot,
      entryPoints: [barrelFile],
      bundle: true,
      write: false,
      format: 'cjs',
      platform: 'browser',
      target: 'es2022',
      external: ['react'],
      charset: 'utf8',
      legalComments: 'none',
      logLevel: 'silent',
    });
  } catch (error) {
    throw new Error(describeBuildFailure(error));
  }
  const source = wrapBundle(result.outputFiles[0].text);
  if (options.write !== false) {
    await mkdir(dirname(outputFile), { recursive: true });
    await writeFile(outputFile, source);
  }
  return { contributions, barrel, output: outputFile, source, bytes: Buffer.byteLength(source) };
}

/** Run the build as a command-line tool. */
async function main() {
  try {
    const result = await buildClient();
    console.log(JSON.stringify({
      ok: true,
      bundle: 'client/client.js',
      barrel: 'client/.build/entry.js',
      bytes: result.bytes,
      pages: result.contributions.pages,
      messages: result.contributions.messages,
      actions: result.contributions.actions,
    }, null, 2));
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}

const invokedDirectly = process.argv[1] !== undefined
  && pathToFileURL(resolve(process.argv[1])).href === import.meta.url;
if (invokedDirectly) await main();
