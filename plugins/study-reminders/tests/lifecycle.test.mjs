import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';
import * as core from '../../study-core/host/index.mjs';
import * as facts from '../../study-facts/host/index.mjs';
import * as reminders from '../host/index.mjs';
import * as shell from '../../study-outcomes/host/index.mjs';
const { Context } = createRequire(new URL('../../../source/deepseek-harness/apps/cli/package.json', import.meta.url))('@deepseek-ai/cordis');

test('reminders waits for facts, unloads independently and restores settings without changing schema', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'p5-reminders-'));
  const ctx = new Context();
  const routes = new Map();
  ctx.provide('tools', { register: () => () => {} });
  ctx.provide('connection', { fetch: { register(route) { routes.set(route.path, route); return () => routes.delete(route.path); } } });
  const fibers = [];
  t.after(async () => { for (const fiber of fibers.reverse()) await fiber.dispose(); await rm(directory, { recursive: true, force: true }); });
  const boot = async (plugin, config = {}) => { const fiber = ctx.plugin(plugin, config); fibers.push(fiber); await fiber; return fiber; };
  await boot(core, { dataDir: directory });
  let fiber = await boot(reminders);
  assert.equal((await ctx.study.call('followup', 'due', {})).code, 'unavailable');
  await boot(facts);
  for (let i = 0; i < 100 && !ctx.study.kernel.database.get("SELECT name FROM sqlite_master WHERE name='study_followup_settings'"); i++) await new Promise(resolve => setTimeout(resolve, 10));
  await boot(shell);
  const settings = await ctx.study.call('followup', 'getSettings', {});
  assert.equal(settings.ok, true, JSON.stringify(settings));
  const saved = await ctx.study.call('followup', 'updateSettings', { ...settings.value.settings, snoozeMinutes: 19 }, { requestId: 'p5-settings' });
  assert.equal(saved.ok, true, JSON.stringify(saved));
  const db = ctx.study.kernel.database;
  const schema = db.all("SELECT name, sql FROM sqlite_master WHERE name LIKE 'study_%' ORDER BY name");
  await fiber.dispose();
  assert.equal(ctx.study.has('followup'), false);
  assert.equal([...routes.keys()].some(path => path.startsWith('/api/study/followup/')), false);
  for (const [ns, method] of [['tasks', 'listTasks'], ['plans', 'list'], ['timer', 'status'], ['outcomes', 'day']]) assert.equal((await ctx.study.call(ns, method, {})).ok, true);
  fiber = await boot(reminders);
  assert.equal((await ctx.study.call('followup', 'getSettings', {})).value.settings.snoozeMinutes, 19);
  assert.deepEqual(db.all("SELECT name, sql FROM sqlite_master WHERE name LIKE 'study_%' ORDER BY name"), schema);
});
